// Generates src/ui/icons.ts with only the marks the site uses (keeps the bundle small).
// Run: node scripts/gen-icons.cjs
const fs = require('fs')
const path = require('path')
const si = require('simple-icons')

const BRANDS = {
  python: 'siPython', apachespark: 'siApachespark', typescript: 'siTypescript', react: 'siReact',
  nodedotjs: 'siNodedotjs', tailwindcss: 'siTailwindcss', mongodb: 'siMongodb', redis: 'siRedis',
  firebase: 'siFirebase', jest: 'siJest', git: 'siGit', palantir: 'siPalantir',
}
// Foundry / AIP tools (and brands Simple Icons doesn't carry) use Blueprint, Palantir's own icon set.
const BLUEPRINT = {
  graph: 'graph', 'data-lineage': 'data-lineage', 'git-repo': 'git-repo', application: 'application',
  'code-block': 'code-block', exchange: 'exchange', 'timeline-bar-chart': 'timeline-bar-chart', map: 'map',
  'predictive-analysis': 'predictive-analysis', chat: 'chat', code: 'code', chart: 'chart', document: 'document',
  learning: 'learning', salesforce: 'cloud',
  // Work pictograms (one per pipeline step).
  envelope: 'envelope', clean: 'clean', home: 'home', 'tick-circle': 'tick-circle', 'send-message': 'send-message',
  import: 'import', 'th-derived': 'th-derived', cube: 'cube',
}

const icons = {}
for (const [key, name] of Object.entries(BRANDS)) icons[key] = { viewBox: '0 0 24 24', paths: [si[name].path] }
const bp = path.join(__dirname, '../node_modules/@blueprintjs/icons/lib/cjs/generated/20px/paths')
for (const [key, name] of Object.entries(BLUEPRINT)) icons[key] = { viewBox: '0 0 20 20', paths: require(path.join(bp, `${name}.js`)).default }

const out = `// Generated by scripts/gen-icons.cjs — do not edit by hand.
// Brands: Simple Icons (CC0). Foundry/AIP tools: Blueprint icons by Palantir (Apache-2.0).

export interface Icon {
  viewBox: string
  paths: string[]
}

export const ICONS: Record<string, Icon> = ${JSON.stringify(icons, null, 2)}
`
fs.writeFileSync(path.join(__dirname, '../src/ui/icons.ts'), out)
console.log('icons:', Object.keys(icons).length)
